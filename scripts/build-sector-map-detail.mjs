#!/usr/bin/env node

/**
 * Build the high-detail state/territory boundaries the sector explorer swaps
 * in once the map is zoomed past ~3x, where the base 0.05-degree
 * generalization turns coastlines blocky.
 *
 * Same source, projection and viewBox as scripts/build-sector-map.mjs; only
 * the generalization tolerance and the small-island cutoff differ. The module
 * is dynamically imported by the explorer so it never enters the base bundle.
 */

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const sourceUrl =
  'https://geo.abs.gov.au/arcgis/rest/services/ASGS2021/STE/FeatureServer/1/query?' +
  new URLSearchParams({
    where: "state_code_2021<'9'",
    outFields: 'state_code_2021',
    returnGeometry: 'true',
    outSR: '4326',
    geometryPrecision: '3',
    maxAllowableOffset: '0.005',
    f: 'geojson',
  });

const jurisdictionByCode = {
  '1': 'NSW',
  '2': 'VIC',
  '3': 'QLD',
  '4': 'SA',
  '5': 'WA',
  '6': 'TAS',
  '7': 'NT',
  '8': 'ACT',
};

const width = 760;
const height = 600;
const bounds = { minLon: 112, maxLon: 154, minLat: -44, maxLat: -9 };

function project([lon, lat]) {
  const x = ((lon - bounds.minLon) / (bounds.maxLon - bounds.minLon)) * width;
  const y = ((bounds.maxLat - lat) / (bounds.maxLat - bounds.minLat)) * height;
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
}

function ringArea(ring) {
  let area = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    area += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  }
  return Math.abs(area / 2);
}

function pathForRing(ring) {
  const points = ring.map(project);
  return `${points.map(([x, y], index) => `${index ? 'L' : 'M'}${x} ${y}`).join('')}Z`;
}

function geometryToPath(geometry, jurisdiction) {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  return polygons
    .filter((polygon) => jurisdiction === 'ACT' || ringArea(polygon[0]) >= 0.001)
    .flatMap((polygon) => polygon.map(pathForRing))
    .join('');
}

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(`ABS boundary request failed: ${response.status} ${response.statusText}`);
}

const geojson = await response.json();
if (!Array.isArray(geojson.features) || geojson.features.length !== 8) {
  throw new Error(`Expected 8 state/territory features, received ${geojson.features?.length ?? 0}`);
}

const paths = {};
for (const feature of geojson.features) {
  const jurisdiction = jurisdictionByCode[feature.properties.state_code_2021];
  paths[jurisdiction] = geometryToPath(feature.geometry, jurisdiction);
}

const output = `/* Generated by scripts/build-sector-map-detail.mjs. Do not edit by hand. */\n` +
  `export const AUSTRALIA_STATE_DETAIL_PATHS: Record<string, string> = ${JSON.stringify(paths)};\n`;

const destination = path.resolve(process.cwd(), 'dashboard/lib/australia-map-detail.ts');
await writeFile(destination, output, 'utf8');
console.log(
  `Wrote detail paths for ${Object.keys(paths).length} jurisdictions ` +
    `(${Math.round(output.length / 1024)} KB) to ${destination}`,
);

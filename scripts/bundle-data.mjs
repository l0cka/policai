// Writes src/lib/bundled-files.generated.ts: the repository data files the
// site reads at request time, keyed by repo-relative path. A Worker has no
// project filesystem, so the Cloudflare build reads them from this module.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOTS = [
	{ dir: "data", match: /\.(json|md)$/ },
	{ dir: "public/data", match: /\.json$/ },
];
const OUT = "src/lib/bundled-files.generated.ts";

async function walk(dir) {
	const entries = await readdir(dir, { withFileTypes: true });
	const nested = await Promise.all(
		entries.map((entry) => {
			const full = path.join(dir, entry.name);
			return entry.isDirectory() ? walk(full) : [full];
		}),
	);
	return nested.flat();
}

const files = {};
for (const { dir, match } of ROOTS) {
	for (const file of (await walk(dir)).filter((name) => match.test(name)).sort()) {
		files[file.split(path.sep).join("/")] = await readFile(file, "utf8");
	}
}

await writeFile(
	OUT,
	`// Generated by scripts/bundle-data.mjs. Do not edit.\nexport const BUNDLED_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files)};\n`,
);
console.log(`bundle-data: ${Object.keys(files).length} files -> ${OUT}`);
